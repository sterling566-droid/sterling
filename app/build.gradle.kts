// Release signing reads from local.properties (never committed - it's in
// .gitignore) or environment variables, so no secret ever lands in the
// repo. See README "Publishing a signed release" for how to fill these in.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun secret(key: String): String? =
    localProps.getProperty(key) ?: System.getenv(key)

